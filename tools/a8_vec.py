def splash_layout(src):
    """Последний шаг цели vec (env A8_SPLASH): редирект той же длиной + код и
    данные заставки. До a8_pack_holes/a8_layout_upper текст не трогаем."""
    if src.count(_SPLASH_CLR) != 1:
        raise SystemExit("a8_splash: якорь цикла очистки в vec_boot не найден однократно")
    if src.count(_SPLASH_MARKER) != 1:
        raise SystemExit("a8_splash: ASSERT нижнего региона не найден однократно")
    src = src.replace(_SPLASH_CLR, _SPLASH_JMP, 1)
    src = src.replace(_SPLASH_MARKER, _SPLASH_CONT + _SPLASH_MARKER, 1)
    src = src.replace(_SPLASH_MARKER, _TUNE_CODE + _SPLASH_MARKER, 1)
    src = src.replace(_SPLASH_MARKER, _SPLASH_MARKER + _TUNE_STATE, 1)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "alien8_splash.bin")
    data = open(path, "rb").read()
    if len(data) != 8192:
        raise SystemExit("a8_splash: src/alien8_splash.bin должен быть 8192 байта (сначала tools/a8_splash.py)")
    lines = ["\n        ORG 0x8000              ; релизная заставка: 8192 Б в раскладке плоскости 0\n"
             "a8_splash:\n"]
    for i in range(0, 8192, 16):
        lines.append("        DB " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + "\n")
    lines.append("        ASSERT a8_splash + 8192 <= 0xA000   ; заставка не должна налезть на vidbuf\n")
    db = "".join(lines)
    tune = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "c64_tune.bin"), "rb").read()
    if len(tune) != 3571:
        raise SystemExit("a8_splash: src/c64_tune.bin должен быть 3571 байт (сначала tools/a8_tune_c64.py)")
    tlines = ["\n        ORG 0xF100              ; мелодия C64: reverse_bits_table и таблицы сдвига строит build_lookup_tbls из START, до него область свободна\n"
              "a8_tune:\n"]
    for i in range(0, len(tune), 16):
        tlines.append("        DB " + ", ".join(f"0x{b:02X}" for b in tune[i:i + 16]) + "\n")
    tlines.append("        ASSERT a8_tune + {} <= 0xFF00   ; мелодия не должна налезть на состояние голосов\n".format(len(tune)))
    db = db + "".join(tlines)
    src, n = re.subn(r'^        SAVEBIN [^\n]*$', lambda m: db + m.group(0), src, count=1, flags=re.M)
    if n != 1:
        raise SystemExit("a8_splash: строка SAVEBIN не найдена")
    return src


def tail():
    t = VEC_TAIL
    t = t.replace("__VEC_KBZX__", _kbzx_table(t), 1)
    # цепочки развёрнутых стековых операций (§12): вход считается по высоте окна, см. fill_window
    t = _sub(t, r'^__A8_FW_CHAIN__\n', "fw_ch:\n" + "\t\t\t\tpush\tde\n" * 16, 'цепочка fw')
    t = _sub(t, r'^__A8_VW_CHAIN__\n', "\t\t\t\tpush\tde\n" * 16, 'цепочка vw')
    t = _sub(t, r'^__A8_US_CHAIN__\n',
             "\t\t\t\tpop\t\tde\n\t\t\t\tld\t\t(hl), e\n\t\t\t\tinc\t\tl\n"
             "\t\t\t\tld\t\t(hl), d\n\t\t\t\tinc\t\tl\n" * 8, 'цепочка us')
    t = _sub(t, r'^__A8_BTS_CHAIN__\n',
             "bts_ch:\n" + "\t\t\t\tpop\t\tde\n\t\t\t\tld\t\t(hl), e\n\t\t\t\tinc\t\tl\n"
             "\t\t\t\tld\t\t(hl), d\n\t\t\t\tinc\t\tl\n" * 16, 'цепочка bts')
    return t
